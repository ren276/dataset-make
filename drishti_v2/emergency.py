"""
drishti_v2/emergency.py
=========================
Two-path emergency vitals (dataset-regeneration-design-memo.md section 6).

Path 1 -- single-vital danger band, any one suffices -> REFER_EMERGENCY +
abstention (the vitals-side counterpart of a Tier-0 routeTo).

Path 2 -- aggregate track-and-trigger, several mildly-abnormal vitals
together raise disposition (typically to REFER_URGENT, to REFER_EMERGENCY
above the upper aggregate threshold) even though none individually breaches.

THRESHOLD_TABLE_VERSION is marked PROVISIONAL per the memo: these are
international early-warning-score-derived numbers, not a reconciled Indian
clinical standard. CBAC/IMCI/IHCI reconciliation is a named build-time
requirement (memo section 6.3) and is NOT done in this build -- it is a
separate, physician-reviewed artifact. Every row generated by this package
carries this version string precisely so a corpus generated under the
provisional table can never be mistaken for one generated under a
reconciled table.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Dict, Optional

from .vitals import VitalTriple, sbp_95th_pediatric, dbp_95th_pediatric

THRESHOLD_TABLE_VERSION = "ews_provisional-0.1.0"

ADULT_AGE_YEARS = 18

# Path 1 -- adult danger/critical bands (provisional, early-warning-score-derived)
ADULT_DANGER = {
    "bp_systolic_max": 90.0,     # <= 90 danger
    "bp_systolic_critical": 70.0,  # <= 70 critical
    "spo2_min": 92.0,            # < 92 danger
    "rr_high": 30.0,             # >= 30
    "rr_low": 9.0,               # < 9
    "hr_high": 130.0,            # >= 130
    "hr_low": 40.0,              # <= 40
    "temp_min": 35.0,            # < 35
}
CHILD_SPO2_MIN = 90.0  # child: IMCI danger signs (tree field) OR SpO2 < 90%


def _true(vitals: Dict[str, VitalTriple], name: str) -> Optional[float]:
    t = vitals.get(name)
    return t.true_value if t is not None else None


def path1_triggered(vitals: Dict[str, VitalTriple], age_years: int,
                     child_danger_sign_present: bool = False) -> bool:
    """
    Evaluated on vitals_true (the generator's ground truth), which is what
    the manifest's GATE-EMERGENCY row counts are audited against. A real
    device would evaluate this on the observed reading; that is a runtime
    behaviour outside this generator's scope.
    """
    if age_years < 18:
        spo2 = _true(vitals, "spo2")
        return child_danger_sign_present or (spo2 is not None and spo2 < CHILD_SPO2_MIN)

    sbp = _true(vitals, "bp_systolic")
    spo2 = _true(vitals, "spo2")
    rr = _true(vitals, "respiratory_rate")
    hr = _true(vitals, "pulse")
    temp = _true(vitals, "temperature")

    if sbp is not None and sbp <= ADULT_DANGER["bp_systolic_max"]:
        return True
    if spo2 is not None and spo2 < ADULT_DANGER["spo2_min"]:
        return True
    if rr is not None and (rr >= ADULT_DANGER["rr_high"] or rr < ADULT_DANGER["rr_low"]):
        return True
    if hr is not None and (hr >= ADULT_DANGER["hr_high"] or hr <= ADULT_DANGER["hr_low"]):
        return True
    if temp is not None and temp < ADULT_DANGER["temp_min"]:
        return True
    return False


# Path 2 -- NEWS2-shaped per-vital ordinal score (0-3), summed. ASSUMED
# aggregate thresholds -- PROVISIONAL, see module docstring.
AGGREGATE_URGENT_MIN = 5
AGGREGATE_EMERGENCY_MIN = 7


def _score_range(value: Optional[float], bands) -> int:
    """bands: list of (score, lo, hi) evaluated in order, first match wins."""
    if value is None:
        return 0
    for score, lo, hi in bands:
        if lo <= value < hi:
            return score
    return 0


def path2_aggregate_score(vitals: Dict[str, VitalTriple]) -> int:
    sbp = _true(vitals, "bp_systolic")
    spo2 = _true(vitals, "spo2")
    rr = _true(vitals, "respiratory_rate")
    hr = _true(vitals, "pulse")
    temp = _true(vitals, "temperature")

    score = 0
    score += _score_range(sbp, [(3, -1e9, 91), (2, 91, 101), (1, 101, 111), (0, 111, 220), (2, 220, 1e9)])
    score += _score_range(spo2, [(3, -1e9, 92), (2, 92, 94), (1, 94, 96), (0, 96, 101)])
    score += _score_range(rr, [(3, -1e9, 9), (0, 9, 12), (1, 20, 21), (2, 21, 25), (3, 25, 1e9), (0, 12, 20)])
    score += _score_range(hr, [(3, -1e9, 41), (1, 41, 51), (0, 51, 91), (1, 91, 111), (2, 111, 131), (3, 131, 1e9)])
    score += _score_range(temp, [(3, -1e9, 35), (1, 35, 36), (0, 36, 38), (1, 38, 39.1), (2, 39.1, 1e9)])
    return score


def path2_disposition(score: int) -> Optional[str]:
    if score >= AGGREGATE_EMERGENCY_MIN:
        return "REFER_EMERGENCY"
    if score >= AGGREGATE_URGENT_MIN:
        return "REFER_URGENT"
    return None
